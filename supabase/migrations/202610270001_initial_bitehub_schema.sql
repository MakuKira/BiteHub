CREATE TABLE bitehub_app.users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  email text NOT NULL,
  password_hash text NOT NULL,
  password_salt text NOT NULL,
  role text NOT NULL CHECK (role IN ('buyer', 'owner', 'runner', 'admin')),
  school_id text NOT NULL DEFAULT 'pns' REFERENCES bitehub_app.schools(id),
  school_region text NOT NULL DEFAULT 'MIMAROPA',
  school_province text NOT NULL DEFAULT 'Palawan',
  school_city text NOT NULL DEFAULT 'Puerto Princesa',
  school_zip text NOT NULL DEFAULT '5300',
  grade_section text NOT NULL DEFAULT '',
  profile_photo_data bytea,
  profile_photo_type text,
  profile_photo_version integer NOT NULL DEFAULT 0 CHECK (profile_photo_version >= 0),
  created_at timestamptz NOT NULL DEFAULT now(),
  deleted_at timestamptz
);

CREATE UNIQUE INDEX users_email_lower_unique_idx ON bitehub_app.users (lower(email));

CREATE TABLE bitehub_app.sessions (
  token_hash text PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES bitehub_app.users(id) ON DELETE CASCADE,
  expires_at bigint NOT NULL
);
CREATE INDEX sessions_expiry_idx ON bitehub_app.sessions (expires_at);

CREATE TABLE bitehub_app.stalls (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id bigint NOT NULL UNIQUE REFERENCES bitehub_app.users(id) ON DELETE CASCADE,
  name text NOT NULL,
  description text NOT NULL DEFAULT '',
  status text NOT NULL DEFAULT 'approved' CHECK (status IN ('pending', 'approved', 'paused')),
  opens_at text NOT NULL DEFAULT '00:00',
  closes_at text NOT NULL DEFAULT '23:59',
  prep_minutes integer NOT NULL DEFAULT 15 CHECK (prep_minutes BETWEEN 1 AND 180),
  pickup_slot_capacity integer NOT NULL DEFAULT 4 CHECK (pickup_slot_capacity BETWEEN 1 AND 100),
  pickup_lat double precision,
  pickup_lon double precision,
  logo_data bytea,
  logo_type text,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE bitehub_app.products (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  stall_id bigint NOT NULL REFERENCES bitehub_app.stalls(id) ON DELETE CASCADE,
  name text NOT NULL,
  description text NOT NULL DEFAULT '',
  ingredients text NOT NULL DEFAULT '',
  category text NOT NULL,
  price_cents integer NOT NULL CHECK (price_cents > 0),
  emoji text NOT NULL DEFAULT '🍽️',
  available boolean NOT NULL DEFAULT true,
  stock_count integer CHECK (stock_count IS NULL OR stock_count >= 0),
  dietary_tags text NOT NULL DEFAULT '[]',
  allergen_tags text NOT NULL DEFAULT '[]',
  photo_data bytea,
  photo_type text,
  created_at timestamptz NOT NULL DEFAULT now(),
  featured_until timestamptz
);
CREATE INDEX products_stall_idx ON bitehub_app.products (stall_id, available);

CREATE TABLE bitehub_app.reach_views (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  stall_id bigint NOT NULL REFERENCES bitehub_app.stalls(id) ON DELETE CASCADE,
  product_id bigint REFERENCES bitehub_app.products(id) ON DELETE CASCADE,
  viewed_on text NOT NULL,
  viewer_key text NOT NULL
);
CREATE UNIQUE INDEX reach_product_daily_viewer_idx
  ON bitehub_app.reach_views (stall_id, product_id, viewed_on, viewer_key)
  WHERE product_id IS NOT NULL;
CREATE UNIQUE INDEX reach_stall_daily_viewer_idx
  ON bitehub_app.reach_views (stall_id, viewed_on, viewer_key)
  WHERE product_id IS NULL;

CREATE TABLE bitehub_app.settings (
  key text PRIMARY KEY,
  value text NOT NULL
);
INSERT INTO bitehub_app.settings (key, value) VALUES ('ordering_paused', 'false')
ON CONFLICT (key) DO NOTHING;

CREATE TABLE bitehub_app.orders (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  buyer_id bigint REFERENCES bitehub_app.users(id),
  stall_id bigint NOT NULL REFERENCES bitehub_app.stalls(id),
  runner_id bigint REFERENCES bitehub_app.users(id),
  fulfillment text NOT NULL CHECK (fulfillment IN ('pickup', 'delivery')),
  status text NOT NULL CHECK (status IN ('placed', 'confirmed', 'preparing', 'ready', 'out', 'completed', 'declined')),
  total_cents integer NOT NULL CHECK (total_cents >= 0),
  buyer_note text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  estimated_ready_at timestamptz,
  pickup_at timestamptz,
  delivery_lat double precision,
  delivery_lon double precision,
  runner_name text NOT NULL DEFAULT '',
  runner_tracking_token_hash text,
  runner_tracking_expires_at timestamptz,
  pickup_offer_status text NOT NULL DEFAULT 'none'
    CHECK (pickup_offer_status IN ('none', 'pending', 'accepted', 'declined')),
  guest_name text NOT NULL DEFAULT '',
  guest_school_role text NOT NULL DEFAULT '',
  guest_grade text NOT NULL DEFAULT '',
  guest_section text NOT NULL DEFAULT '',
  guest_access_token_hash text NOT NULL DEFAULT '',
  guest_pickup_code text NOT NULL DEFAULT ''
);
CREATE INDEX orders_buyer_idx ON bitehub_app.orders (buyer_id, id DESC);
CREATE INDEX orders_stall_idx ON bitehub_app.orders (stall_id, id DESC);
CREATE INDEX orders_runner_idx ON bitehub_app.orders (runner_id, id DESC);
CREATE UNIQUE INDEX orders_guest_pickup_code_idx
  ON bitehub_app.orders (guest_pickup_code)
  WHERE guest_pickup_code <> '';

CREATE TABLE bitehub_app.order_items (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id bigint NOT NULL REFERENCES bitehub_app.orders(id) ON DELETE CASCADE,
  product_id bigint REFERENCES bitehub_app.products(id) ON DELETE SET NULL,
  name text NOT NULL,
  price_cents integer NOT NULL CHECK (price_cents >= 0),
  quantity integer NOT NULL CHECK (quantity BETWEEN 1 AND 50),
  emoji text NOT NULL
);

CREATE TABLE bitehub_app.feedback (
  order_id bigint PRIMARY KEY REFERENCES bitehub_app.orders(id) ON DELETE CASCADE,
  buyer_id bigint NOT NULL REFERENCES bitehub_app.users(id) ON DELETE CASCADE,
  rating integer NOT NULL CHECK (rating BETWEEN 1 AND 5),
  comment text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE bitehub_app.delivery_positions (
  order_id bigint PRIMARY KEY REFERENCES bitehub_app.orders(id) ON DELETE CASCADE,
  latitude double precision NOT NULL CHECK (latitude BETWEEN -90 AND 90),
  longitude double precision NOT NULL CHECK (longitude BETWEEN -180 AND 180),
  accuracy double precision,
  heading double precision,
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE bitehub_app.push_subscriptions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES bitehub_app.users(id) ON DELETE CASCADE,
  endpoint text NOT NULL UNIQUE,
  subscription_json text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

-- Present in the local SQLite file but not used by the current Python routes.
-- Keep the structure available so a future data import can preserve old requests.
CREATE TABLE bitehub_app.school_requests (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  school_name text NOT NULL,
  school_type text NOT NULL,
  region text NOT NULL,
  province text NOT NULL,
  city text NOT NULL,
  zip text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now()
);

-- Separate database roles for the first catalog-only connection and the later
-- full BiteHub API connection. Login users and passwords are configured
-- separately and must never be committed to this repository.
CREATE ROLE bitehub_catalog_reader NOLOGIN NOBYPASSRLS;
CREATE ROLE bitehub_backend NOLOGIN NOBYPASSRLS;
GRANT USAGE ON SCHEMA bitehub_app TO bitehub_catalog_reader, bitehub_backend;

GRANT SELECT ON TABLE bitehub_app.schools, bitehub_app.stalls, bitehub_app.products
  TO bitehub_catalog_reader;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE
  bitehub_app.schools, bitehub_app.users, bitehub_app.sessions, bitehub_app.stalls, bitehub_app.products,
  bitehub_app.reach_views, bitehub_app.settings, bitehub_app.orders, bitehub_app.order_items,
  bitehub_app.feedback, bitehub_app.delivery_positions, bitehub_app.push_subscriptions,
  bitehub_app.school_requests
TO bitehub_backend;
GRANT USAGE, SELECT ON SEQUENCE
  bitehub_app.users_id_seq, bitehub_app.stalls_id_seq, bitehub_app.products_id_seq,
  bitehub_app.reach_views_id_seq, bitehub_app.orders_id_seq, bitehub_app.order_items_id_seq,
  bitehub_app.push_subscriptions_id_seq, bitehub_app.school_requests_id_seq
TO bitehub_backend;

-- Enable RLS everywhere. The website must go through the Python API. These
-- revocations prevent anon/authenticated browser roles from reading or changing
-- account, guest-order, delivery, or settings data through Supabase Data API.
ALTER TABLE bitehub_app.schools ENABLE ROW LEVEL SECURITY;
ALTER TABLE bitehub_app.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE bitehub_app.sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE bitehub_app.stalls ENABLE ROW LEVEL SECURITY;
ALTER TABLE bitehub_app.products ENABLE ROW LEVEL SECURITY;
ALTER TABLE bitehub_app.reach_views ENABLE ROW LEVEL SECURITY;
ALTER TABLE bitehub_app.settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE bitehub_app.orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE bitehub_app.order_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE bitehub_app.feedback ENABLE ROW LEVEL SECURITY;
ALTER TABLE bitehub_app.delivery_positions ENABLE ROW LEVEL SECURITY;
ALTER TABLE bitehub_app.push_subscriptions ENABLE ROW LEVEL SECURITY;
ALTER TABLE bitehub_app.school_requests ENABLE ROW LEVEL SECURITY;

-- Read-only pilot access: only the public catalog, only approved stalls, and
-- only available products belonging to approved stalls.
CREATE POLICY bitehub_catalog_schools_read ON bitehub_app.schools
  FOR SELECT TO bitehub_catalog_reader USING (true);
CREATE POLICY bitehub_catalog_stalls_read ON bitehub_app.stalls
  FOR SELECT TO bitehub_catalog_reader USING (status = 'approved');
CREATE POLICY bitehub_catalog_products_read ON bitehub_app.products
  FOR SELECT TO bitehub_catalog_reader
  USING (
    available = true
    AND EXISTS (
      SELECT 1 FROM bitehub_app.stalls s
      WHERE s.id = products.stall_id AND s.status = 'approved'
    )
  );

-- The backend group has table access but still runs with RLS enabled. It is a
-- trusted server role, not an end-user role; Python route checks remain required.
CREATE POLICY bitehub_backend_schools_all ON bitehub_app.schools
  FOR ALL TO bitehub_backend USING (true) WITH CHECK (true);
CREATE POLICY bitehub_backend_users_all ON bitehub_app.users
  FOR ALL TO bitehub_backend USING (true) WITH CHECK (true);
CREATE POLICY bitehub_backend_sessions_all ON bitehub_app.sessions
  FOR ALL TO bitehub_backend USING (true) WITH CHECK (true);
CREATE POLICY bitehub_backend_stalls_all ON bitehub_app.stalls
  FOR ALL TO bitehub_backend USING (true) WITH CHECK (true);
CREATE POLICY bitehub_backend_products_all ON bitehub_app.products
  FOR ALL TO bitehub_backend USING (true) WITH CHECK (true);
CREATE POLICY bitehub_backend_reach_views_all ON bitehub_app.reach_views
  FOR ALL TO bitehub_backend USING (true) WITH CHECK (true);
CREATE POLICY bitehub_backend_settings_all ON bitehub_app.settings
  FOR ALL TO bitehub_backend USING (true) WITH CHECK (true);
CREATE POLICY bitehub_backend_orders_all ON bitehub_app.orders
  FOR ALL TO bitehub_backend USING (true) WITH CHECK (true);
CREATE POLICY bitehub_backend_order_items_all ON bitehub_app.order_items
  FOR ALL TO bitehub_backend USING (true) WITH CHECK (true);
CREATE POLICY bitehub_backend_feedback_all ON bitehub_app.feedback
  FOR ALL TO bitehub_backend USING (true) WITH CHECK (true);
CREATE POLICY bitehub_backend_delivery_positions_all ON bitehub_app.delivery_positions
  FOR ALL TO bitehub_backend USING (true) WITH CHECK (true);
CREATE POLICY bitehub_backend_push_subscriptions_all ON bitehub_app.push_subscriptions
  FOR ALL TO bitehub_backend USING (true) WITH CHECK (true);
CREATE POLICY bitehub_backend_school_requests_all ON bitehub_app.school_requests
  FOR ALL TO bitehub_backend USING (true) WITH CHECK (true);

REVOKE ALL ON TABLE
  bitehub_app.schools, bitehub_app.users, bitehub_app.sessions, bitehub_app.stalls, bitehub_app.products,
  bitehub_app.reach_views, bitehub_app.settings, bitehub_app.orders, bitehub_app.order_items,
  bitehub_app.feedback, bitehub_app.delivery_positions, bitehub_app.push_subscriptions,
  bitehub_app.school_requests
FROM PUBLIC, anon, authenticated, service_role;

REVOKE ALL ON SEQUENCE
  bitehub_app.users_id_seq, bitehub_app.stalls_id_seq, bitehub_app.products_id_seq,
  bitehub_app.reach_views_id_seq, bitehub_app.orders_id_seq, bitehub_app.order_items_id_seq,
  bitehub_app.push_subscriptions_id_seq, bitehub_app.school_requests_id_seq
FROM PUBLIC, anon, authenticated, service_role;

COMMIT;
