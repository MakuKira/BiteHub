-- BiteHub baseline schema for Supabase PostgreSQL.
-- This is a local migration draft. Review and apply to a development project first.
-- The Python API remains the trusted application layer; browser clients must not
-- query these tables directly.

BEGIN;

-- Keep the current Supabase public schema and its older tables untouched.
-- Do not add bitehub_app to the Data API's exposed schemas.
CREATE SCHEMA bitehub_app;
REVOKE ALL ON SCHEMA bitehub_app FROM PUBLIC, anon, authenticated, service_role;

CREATE TABLE bitehub_app.schools (
  id text PRIMARY KEY,
  name text NOT NULL,
  school_type text NOT NULL,
  region text NOT NULL,
  province text NOT NULL,
  city text NOT NULL,
  latitude double precision,
  longitude double precision,
  delivery_radius_m integer NOT NULL DEFAULT 1500 CHECK (delivery_radius_m > 0),
  created_at timestamptz NOT NULL DEFAULT now()
);

INSERT INTO bitehub_app.schools
