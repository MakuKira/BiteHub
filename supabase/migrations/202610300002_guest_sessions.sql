-- Store each anonymous guest session with a generated ID, and associate guest
-- orders with that session. The raw browser token is never stored in PostgreSQL.

BEGIN;

CREATE TABLE IF NOT EXISTS bitehub_app.guest_sessions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  guest_name text NOT NULL,
  token_hash text NOT NULL UNIQUE,
  created_at timestamptz NOT NULL DEFAULT now(),
  expires_at bigint NOT NULL
);

CREATE INDEX IF NOT EXISTS guest_sessions_expiry_idx
  ON bitehub_app.guest_sessions (expires_at);

ALTER TABLE bitehub_app.orders
  ADD COLUMN IF NOT EXISTS guest_session_id bigint
  REFERENCES bitehub_app.guest_sessions(id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS orders_guest_session_idx
  ON bitehub_app.orders (guest_session_id);

ALTER TABLE bitehub_app.guest_sessions ENABLE ROW LEVEL SECURITY;
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = 'bitehub_app'
      AND tablename = 'guest_sessions'
      AND policyname = 'bitehub_backend_guest_sessions_all'
  ) THEN
    CREATE POLICY bitehub_backend_guest_sessions_all ON bitehub_app.guest_sessions
      FOR ALL TO bitehub_backend USING (true) WITH CHECK (true);
  END IF;
END
$$;

GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE bitehub_app.guest_sessions TO bitehub_backend;
GRANT USAGE, SELECT ON SEQUENCE bitehub_app.guest_sessions_id_seq TO bitehub_backend;
REVOKE ALL ON TABLE bitehub_app.guest_sessions FROM PUBLIC, anon, authenticated, service_role;

COMMIT;
