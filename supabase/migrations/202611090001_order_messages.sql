-- Private, order-scoped in-app conversation between a customer/guest and the
-- stall owner. The Python backend checks the order session before reading or
-- writing; browser roles receive no direct table access.

BEGIN;

CREATE TABLE IF NOT EXISTS bitehub_app.order_messages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id bigint NOT NULL
    REFERENCES bitehub_app.orders(id) ON DELETE CASCADE,
  sender_role text NOT NULL
    CHECK (sender_role IN ('guest', 'buyer', 'owner')),
  sender_user_id bigint
    REFERENCES bitehub_app.users(id) ON DELETE SET NULL,
  sender_name varchar(80) NOT NULL,
  message varchar(1000) NOT NULL
    CHECK (char_length(message) BETWEEN 1 AND 1000),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS order_messages_order_idx
  ON bitehub_app.order_messages (order_id, id);

ALTER TABLE bitehub_app.order_messages ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = 'bitehub_app'
      AND tablename = 'order_messages'
      AND policyname = 'bitehub_backend_order_messages_all'
  ) THEN
    CREATE POLICY bitehub_backend_order_messages_all
      ON bitehub_app.order_messages
      FOR ALL TO bitehub_backend
      USING (true) WITH CHECK (true);
  END IF;
END
$$;

GRANT SELECT, INSERT, UPDATE, DELETE
  ON TABLE bitehub_app.order_messages TO bitehub_backend;
GRANT USAGE, SELECT
  ON SEQUENCE bitehub_app.order_messages_id_seq TO bitehub_backend;
REVOKE ALL ON TABLE bitehub_app.order_messages
  FROM PUBLIC, anon, authenticated, service_role;

COMMIT;
