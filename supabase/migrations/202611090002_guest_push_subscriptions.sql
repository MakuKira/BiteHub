-- Device alerts for anonymous guest sessions. The backend binds subscriptions
-- to the HttpOnly guest-session cookie and never exposes this table to clients.

BEGIN;

CREATE TABLE IF NOT EXISTS bitehub_app.guest_push_subscriptions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  guest_session_id bigint NOT NULL
    REFERENCES bitehub_app.guest_sessions(id) ON DELETE CASCADE,
  endpoint text NOT NULL UNIQUE,
  subscription_json text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS guest_push_subscriptions_session_idx
  ON bitehub_app.guest_push_subscriptions (guest_session_id);

ALTER TABLE bitehub_app.guest_push_subscriptions ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = 'bitehub_app'
      AND tablename = 'guest_push_subscriptions'
      AND policyname = 'bitehub_backend_guest_push_subscriptions_all'
  ) THEN
    CREATE POLICY bitehub_backend_guest_push_subscriptions_all
      ON bitehub_app.guest_push_subscriptions
      FOR ALL TO bitehub_backend
      USING (true) WITH CHECK (true);
  END IF;
END
$$;

GRANT SELECT, INSERT, UPDATE, DELETE
  ON TABLE bitehub_app.guest_push_subscriptions TO bitehub_backend;
GRANT USAGE, SELECT
  ON SEQUENCE bitehub_app.guest_push_subscriptions_id_seq TO bitehub_backend;
REVOKE ALL ON TABLE bitehub_app.guest_push_subscriptions
  FROM PUBLIC, anon, authenticated, service_role;

COMMIT;
