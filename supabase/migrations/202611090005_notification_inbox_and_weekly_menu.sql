-- Persistent notification inbox and recurring weekly menu plans.
-- Safe to rerun if a previous attempt stopped partway through.
-- The Python backend scopes every read and write to its verified session;
-- browser roles never receive direct table access.

BEGIN;

CREATE TABLE IF NOT EXISTS bitehub_app.notifications (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint REFERENCES bitehub_app.users(id) ON DELETE CASCADE,
  guest_session_id bigint REFERENCES bitehub_app.guest_sessions(id) ON DELETE CASCADE,
  title varchar(120) NOT NULL CHECK (char_length(title) BETWEEN 1 AND 120),
  body varchar(500) NOT NULL DEFAULT '',
  url varchar(500) NOT NULL DEFAULT '/',
  tag varchar(120) NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now(),
  read_at timestamptz,
  CHECK ((user_id IS NOT NULL AND guest_session_id IS NULL) OR
         (user_id IS NULL AND guest_session_id IS NOT NULL))
);

CREATE INDEX IF NOT EXISTS notifications_user_unread_idx
  ON bitehub_app.notifications (user_id, read_at, id DESC);
CREATE INDEX IF NOT EXISTS notifications_guest_unread_idx
  ON bitehub_app.notifications (guest_session_id, read_at, id DESC);

ALTER TABLE bitehub_app.notifications ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = 'bitehub_app'
      AND tablename = 'notifications'
      AND policyname = 'bitehub_backend_notifications_all'
  ) THEN
    CREATE POLICY bitehub_backend_notifications_all
      ON bitehub_app.notifications
      FOR ALL TO bitehub_backend
      USING (true) WITH CHECK (true);
  END IF;
END;
$$;

GRANT SELECT, INSERT, UPDATE, DELETE
  ON TABLE bitehub_app.notifications TO bitehub_backend;
GRANT USAGE, SELECT
  ON SEQUENCE bitehub_app.notifications_id_seq TO bitehub_backend;
REVOKE ALL ON TABLE bitehub_app.notifications
  FROM PUBLIC, anon, authenticated, service_role;

CREATE TABLE IF NOT EXISTS bitehub_app.weekly_menu_slots (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  stall_id bigint NOT NULL REFERENCES bitehub_app.stalls(id) ON DELETE CASCADE,
  product_id bigint NOT NULL REFERENCES bitehub_app.products(id) ON DELETE CASCADE,
  weekday smallint NOT NULL CHECK (weekday BETWEEN 0 AND 6),
  service_period text NOT NULL CHECK (service_period IN ('Morning break', 'Lunch', 'Afternoon break')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (stall_id, product_id, weekday, service_period)
);

CREATE INDEX IF NOT EXISTS weekly_menu_weekday_idx
  ON bitehub_app.weekly_menu_slots (weekday, service_period, stall_id);

ALTER TABLE bitehub_app.weekly_menu_slots ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = 'bitehub_app'
      AND tablename = 'weekly_menu_slots'
      AND policyname = 'bitehub_backend_weekly_menu_all'
  ) THEN
    CREATE POLICY bitehub_backend_weekly_menu_all
      ON bitehub_app.weekly_menu_slots
      FOR ALL TO bitehub_backend
      USING (true) WITH CHECK (true);
  END IF;
END;
$$;

GRANT SELECT, INSERT, UPDATE, DELETE
  ON TABLE bitehub_app.weekly_menu_slots TO bitehub_backend;
GRANT USAGE, SELECT
  ON SEQUENCE bitehub_app.weekly_menu_slots_id_seq TO bitehub_backend;
REVOKE ALL ON TABLE bitehub_app.weekly_menu_slots
  FROM PUBLIC, anon, authenticated, service_role;

COMMIT;
