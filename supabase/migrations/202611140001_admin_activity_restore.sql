-- Private admin action history with a time-limited restore path for catalog removals.
-- Apply to BiteHub-Dev first. Removed food stays in products so order history remains linked.

BEGIN;

ALTER TABLE bitehub_app.products
  ADD COLUMN IF NOT EXISTS deleted_at timestamptz;

CREATE TABLE IF NOT EXISTS bitehub_app.admin_activity (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_user_id bigint REFERENCES bitehub_app.users(id) ON DELETE SET NULL,
  actor_label text NOT NULL,
  action text NOT NULL,
  target_type text NOT NULL,
  target_id bigint,
  target_label text NOT NULL,
  details_json text NOT NULL DEFAULT '{}',
  created_at timestamptz NOT NULL DEFAULT now(),
  restored_at timestamptz,
  restored_by bigint REFERENCES bitehub_app.users(id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS admin_activity_created_idx
  ON bitehub_app.admin_activity (created_at DESC, id DESC);

ALTER TABLE bitehub_app.admin_activity ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = 'bitehub_app'
      AND tablename = 'admin_activity'
      AND policyname = 'bitehub_backend_admin_activity_all'
  ) THEN
    CREATE POLICY bitehub_backend_admin_activity_all
      ON bitehub_app.admin_activity
      FOR ALL TO bitehub_backend
      USING (true) WITH CHECK (true);
  END IF;
END;
$$;

GRANT SELECT, INSERT, UPDATE, DELETE
  ON TABLE bitehub_app.admin_activity TO bitehub_backend;
GRANT USAGE, SELECT
  ON SEQUENCE bitehub_app.admin_activity_id_seq TO bitehub_backend;
REVOKE ALL ON TABLE bitehub_app.admin_activity
  FROM PUBLIC, anon, authenticated, service_role;

COMMIT;
